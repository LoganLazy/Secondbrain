import test from 'node:test'
import assert from 'node:assert/strict'
import { searchSnippet } from '../src/libraryUtils.js'

test('snippet centers around a match beyond the start of the passage', () => {
  const text = 'x'.repeat(500) + ' target evidence ' + 'y'.repeat(500)
  const parts = searchSnippet(text, 'target')
  assert.equal(parts.find(part => part.hit).text, 'target')
  assert.ok(parts.map(part => part.text).join('').startsWith('…'))
  assert.ok(parts.map(part => part.text).join('').length <= 282)
})

test('regular expression punctuation is treated as literal text', () => {
  const parts = searchSnippet('before [.*] after', '[.*]')
  assert.deepEqual(parts.filter(part => part.hit).map(part => part.text), ['[.*]'])
})

test('HTML-like content remains text, never markup generated by the helper', () => {
  const text = '<img src=x onerror=alert(1)> evidence'
  const parts = searchSnippet(text, 'img')
  assert.equal(parts.map(part => part.text).join(''), text)
  assert.deepEqual(Object.keys(parts[0]).sort(), ['hit', 'text'])
})

test('multiple query words are highlighted case-insensitively', () => {
  assert.deepEqual(searchSnippet('Alpha and BETA', 'alpha beta').filter(part => part.hit).map(part => part.text), ['Alpha', 'BETA'])
})

test('empty query and no match produce bounded unmarked snippets', () => {
  for (const query of ['', 'absent']) {
    const parts = searchSnippet('hello '.repeat(100), query)
    assert.ok(parts.every(part => !part.hit))
    assert.ok(parts.map(part => part.text).join('').length <= 281)
  }
})
