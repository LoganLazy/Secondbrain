export function t(key, vars) {
  let s = (DICT[lang.value] && DICT[lang.value][key]) || DICT.zh[key] || key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replace(`{${k}}`, v).replace(`{${k.toLowerCase()}}`, String(v).toLowerCase())
        .replace(`{${k.charAt(0)}${k.slice(1)}}`, v)
    }
  }
  return s
}
